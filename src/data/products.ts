/** Placeholder shown for any spec that has no confirmed source yet. */
export const SPEC_PENDING = "확인 중";

/**
 * "active" is the only status shown to shoppers in the catalog. "draft" is
 * an admin-only work-in-progress listing. "outOfStock" is set automatically
 * when `stock` is depleted by a purchase (see ProductService.decrementStock)
 * — an admin restocks by editing stock and/or status back to "active".
 */
export type ProductStatus = "active" | "draft" | "outOfStock";

export interface Product {
  /** URL slug, unique per product */
  id: string;
  /** Refrigerator model code */
  model: string;
  /** Demo price in South Korean won (KRW), stored as a plain number. Format for display separately (see src/lib/currency.ts). */
  price: number;
  /** Hero image shown on the catalog card and as the default detail-page image */
  mainImage: string;
  /** All available images for this model, public/-relative paths */
  images: string[];
  /** Manufacturer brand. Only filled in when visibly confirmed in the product photos. */
  brand: string;
  /** Storage capacity (e.g. liters). */
  capacity: string;
  /** Overall dimensions (W x D x H). */
  dimensions: string;
  /** Door/finish color. */
  color: string;
  /** Energy efficiency grade. */
  energyGrade: string;
  /** Door configuration (e.g. 2-door, 4-door). */
  doorType: string;
  /** Country where the unit is manufactured. */
  countryOfOrigin: string;
  /** Warranty terms. */
  warranty: string;
  /** Total storage capacity (e.g. liters). */
  totalCapacity: string;
  /** Refrigerator compartment capacity. */
  fridgeCapacity: string;
  /** Freezer compartment capacity. */
  freezerCapacity: string;
  /** Manufacturer name, independent of the marketing brand. */
  manufacturer: string;
  /** Release date / launch information. */
  releaseInfo: string;
  /** Key feature bullet points; empty array until confirmed. */
  keyFeatures: string[];
  /** Full marketing product name (series/line), e.g. "Bespoke AI 냉장고 4도어 키친핏 Max". */
  productName: string;
  /** Product type / line, e.g. "Bespoke AI 냉장고". */
  productType: string;
  /** Installation type, e.g. "키친핏 Max". */
  installationType: string;
  /** Monthly power consumption. */
  monthlyPowerConsumption: string;
  /** Rated voltage / frequency. */
  ratedVoltage: string;
  /** Compressor type. */
  compressor: string;
  /** Refrigerant type. */
  refrigerant: string;
  /** Cooling method. */
  coolingType: string;
  /** Product weight. */
  weight: string;
  /** Door design (e.g. "플랫 도어"). */
  doorDesign: string;
  /** Water/ice dispenser presence or type. */
  dispenser: string;
  /** Ice maker type. */
  iceMaker: string;
  /** Wi-Fi support. */
  wifi: string;
  /** SmartThings support. */
  smartThings: string;
  /** Exterior material/finish (distinct from color). */
  material: string;
  /** Overall dimensions including the rear handle. */
  dimensionsWithHandle: string;
  /** Overall dimensions excluding the rear handle. */
  dimensionsWithoutHandle: string;
  /** Ice type produced (e.g. cube). */
  iceType: string;
  /** Deodorizing / odor-control feature. */
  deodorizing: string;
  /** Built-in display (e.g. Family Hub screen). */
  display: string;
  /** Food showcase compartment presence/side. */
  foodShowcase: string;
  /** Bixby voice assistant support. */
  bixby: string;
  /** Automatic door opening support. */
  autoDoorOpen: string;
  /** AI Vision Inside camera feature support. */
  aiVisionInside: string;
  /** Transparent showcase compartment presence/side. */
  transparentShowcase: string;
  /** Beverage zone compartment presence/side. */
  beverageZone: string;
  /** Interior lighting type (e.g. LED). */
  interiorLighting: string;
  /** Door material/finish (e.g. "네이처 (메탈)"). */
  doorMaterial: string;
  /** Handle type (e.g. "포켓 핸들"). */
  handleType: string;
  /** Smart Diagnosis feature support. */
  smartDiagnosis: string;
  /** Depth only, excluding the rear handle. */
  depthWithoutHandle: string;
  /** Internal layout type (e.g. "상냉장 / 하냉동"). */
  layoutType: string;
  /** Operating noise level. */
  noiseLevel: string;
  /** LG Magic Space convertible compartment feature. */
  magicSpace: string;
  /** LG UP appliance (upgradable) support. */
  upAppliance: string;
  /** Free-text notes; empty when there is nothing to add. */
  notes: string;
  /** Units currently available. 0 blocks Add to Cart / Checkout. */
  stock: number;
  /** Catalog visibility + inventory state; see ProductStatus. */
  status: ProductStatus;
}

/** Official Korean corporate name for a confirmed brand; falls back to SPEC_PENDING when brand isn't confirmed. */
export function getBrandDisplayName(brand: string): string {
  if (brand === "LG") return "LG전자";
  if (brand === "Samsung") return "삼성전자";
  return SPEC_PENDING;
}

/** Official English corporate name for a confirmed brand; null when brand isn't confirmed. */
export function getBrandEnglishName(brand: string): string | null {
  if (brand === "LG") return "LG Electronics";
  if (brand === "Samsung") return "Samsung Electronics";
  return null;
}

/**
 * Compact "highlight" facts for a product, built only from fields that are
 * actually confirmed (never SPEC_PENDING). Returns an empty array when
 * nothing is confirmed yet, rather than inventing placeholder highlights.
 */
export function getProductHighlights(product: Product): { label: string; value: string }[] {
  const candidates: { label: string; value: string }[] = [
    { label: "용량", value: product.capacity },
    { label: "도어 타입", value: product.doorType },
    { label: "색상", value: product.color },
    { label: "에너지 소비효율등급", value: product.energyGrade },
  ];
  return candidates.filter((item) => item.value && item.value !== SPEC_PENDING);
}

/** Compact at-a-glance spec rows shown near the model number on cards and the product page. */
export function getProductInfoRows(product: Product): { label: string; value: string }[] {
  return [
    { label: "브랜드", value: getBrandDisplayName(product.brand) },
    { label: "모델명", value: product.model },
    { label: "제품 유형", value: "냉장고" },
    { label: "용량", value: product.capacity },
    { label: "도어 타입", value: product.doorType },
    { label: "색상", value: product.color },
    { label: "에너지 소비효율등급", value: product.energyGrade },
  ];
}

/** "브랜드 모델명" for confirmed brands (e.g. "LG전자 B502S53"); falls back to just the model when brand isn't confirmed. */
export function getProductFullName(product: Product): string {
  const brand = getBrandDisplayName(product.brand);
  return brand === SPEC_PENDING ? product.model : `${brand} ${product.model}`;
}

/** SEO-friendly description built only from confirmed fields; never invents specs. */
export function getProductDescription(product: Product): string {
  const fullName = getProductFullName(product);
  const highlights = getProductHighlights(product);

  if (highlights.length > 0) {
    const specText = highlights.map((item) => `${item.label} ${item.value}`).join(", ");
    return `${fullName} 냉장고의 ${specText} 정보를 FrostMarket에서 확인해 보세요.`;
  }
  return `${fullName} 냉장고의 실제 제품 이미지와 상세 정보를 FrostMarket에서 확인해 보세요.`;
}

